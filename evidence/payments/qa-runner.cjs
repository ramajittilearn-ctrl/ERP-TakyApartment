const fs = require('node:fs');
const { createRequire } = require('node:module');
const { spawnSync } = require('node:child_process');
const base = '/private/tmp/taky-payment-qa2';
const root = '/private/tmp/taky-payment-development';
const privateEnv = Object.fromEntries(fs.readFileSync(base + '/private.env', 'utf8').trim().split('\n').map(line => { const i = line.indexOf('='); return [line.slice(0,i), line.slice(i+1)]; }));
const identity = JSON.parse(fs.readFileSync(base + '/identity.json', 'utf8'));
const { Client } = createRequire(root + '/package.json')('pg');
(async () => {
  const client = new Client({ connectionString: privateEnv.DATABASE_URL });
  await client.connect();
  const response = await client.query("SELECT current_database() AS database, current_user AS role, (SELECT count(*)::int FROM information_schema.tables WHERE table_schema='public') AS public_tables");
  await client.end();
  if (response.rows[0].database !== identity.database || response.rows[0].role !== identity.role) throw new Error('Synthetic database identity mismatch');
  console.log(JSON.stringify({verified: true, ...response.rows[0], host: identity.host, port: identity.port}));
  const args = process.argv.slice(2);
  if (!args.length) return;
  const permitted = {rehearsal: ['node_modules/.bin/tsx', 'tests/integration/payments-migration-rehearsal.ts'], integration: ['node_modules/.bin/vitest','run','--config','vitest.integration.config.ts','tests/integration/payments.test.ts']};
  if (!permitted[args[0]]) throw new Error('Unsupported QA command');
  if (args[0] === 'rehearsal' && response.rows[0].public_tables !== 0) throw new Error('Rehearsal requires pristine database');
  const [command,...commandArgs] = permitted[args[0]];
  const result = spawnSync(command, commandArgs, {cwd: root, env: {...process.env, DATABASE_URL: privateEnv.DATABASE_URL, DOTENV_CONFIG_PATH: '/dev/null'}, encoding: 'utf8'});
  const clean = value => (value || '').replaceAll(privateEnv.DATABASE_URL, '[synthetic database URL]').replaceAll(privateEnv.QA_PASSWORD, '[redacted]');
  const output = clean(result.stdout) + clean(result.stderr);
  const attempt = new Date().toISOString().replaceAll(':', '-') + '-' + require('node:crypto').randomUUID();
  const artifact = root + '/evidence/payments/qa-' + args[0] + '-' + attempt + '.log';
  fs.writeFileSync(artifact, output, {flag: 'wx'});
  fs.copyFileSync(artifact, root + '/evidence/payments/qa-' + args[0] + '.log');
  console.info('Immutable QA evidence: ' + artifact);
  process.stdout.write(output);
  if (result.error) console.error(result.error.message);
  process.exitCode = result.status ?? 1;
})().catch(error => { console.error(String(error).replaceAll(privateEnv.DATABASE_URL, '[synthetic database URL]').replaceAll(privateEnv.QA_PASSWORD, '[redacted]')); process.exitCode = 1; });
